// Build-time scan: users receive bundled media, never a runtime file picker.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
function buildMusicCatalog(){
  const policyPath=path.join(root,'config','music-library-policy.json');
  if(!fs.existsSync(policyPath))throw Error('Chưa chốt chính sách thư viện nhạc với người dùng.');
  const policy=JSON.parse(fs.readFileSync(policyPath,'utf8'));
  if(typeof policy.deduplicate!=='boolean'||policy.skipInvalid!==true)throw Error('Thiếu lựa chọn xử lý bài trùng/tệp lỗi.');
  const sources=JSON.parse(fs.readFileSync(path.join(root,'config','music-sources.json'),'utf8')).sources;
  const audit=JSON.parse(fs.readFileSync(path.join(root,'qa','audio-audit.json'),'utf8'));
  if(JSON.stringify(audit.folders)!==JSON.stringify(sources.map(s=>s.folder)))throw Error('Cấu hình nguồn nhạc đã thay đổi; chạy audit-audio.js lại.');
  const currentFiles=audit.folders.flatMap(folder=>fs.readdirSync(path.join(root,'Sound',folder)).filter(name=>fs.statSync(path.join(root,'Sound',folder,name)).isFile()).map(name=>['Sound',folder,name].join('/'))).sort();
  const auditedFiles=audit.entries.map(entry=>entry.path).sort();
  if(JSON.stringify(currentFiles)!==JSON.stringify(auditedFiles))throw Error('Danh sách tệp đã thay đổi; chạy scripts/audit-audio.js trước khi đóng gói.');
  const directory=path.resolve(root,'Sound','bundled-music');
  if(!directory.startsWith(path.resolve(root,'Sound')+path.sep))throw Error('Đường dẫn đóng gói không hợp lệ.');
  fs.mkdirSync(directory,{recursive:true});
  const categories=[...new Set(sources.map(s=>s.category))];
  const songs=[],excluded=[],duplicates=[],seen=new Map(),seenNames=new Map(),assets=new Set();
  for(const entry of audit.entries){
    const source=path.resolve(root,entry.path);
    if(!source.startsWith(path.resolve(root,'Sound')+path.sep))throw Error('Tệp ngoài thư mục Sound.');
    const hash=crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex');
    if(hash!==entry.sha256)throw Error('Tệp đã thay đổi, chạy audit-audio.js lại: '+entry.path);
    if(!entry.valid){excluded.push({path:entry.path,reason:entry.error});continue;}
    if(policy.deduplicate&&seen.has(hash)){duplicates.push({path:entry.path,kept:seen.get(hash)});continue;}
    const title=entry.file.replace(/\.[^.]+$/,'').normalize('NFC').trim();
    if(policy.deduplicate&&seenNames.has(title)){duplicates.push({path:entry.path,kept:seenNames.get(title),reason:'same-title'});continue;}
    seen.set(hash,entry.path);seenNames.set(title,entry.path);
    const filename=hash+path.extname(entry.file).toLowerCase();assets.add(filename);
    fs.copyFileSync(source,path.join(directory,filename));
    songs.push({id:'preset_song_bundle_'+crypto.createHash('sha256').update(entry.path).digest('hex').slice(0,20),name:entry.file.replace(/\.[^.]+$/,''),category:sources.find(s=>s.folder===entry.folder).category,url:'Sound/bundled-music/'+filename,size:entry.size,duration:entry.duration,isPreset:true});
  }
  // Only generated files in this checked directory are pruned; original folders stay intact.
  for(const file of fs.readdirSync(directory))if(/^[a-f0-9]{64}\.(mp3|m4a|wav|mp4)$/.test(file)&&!assets.has(file))fs.unlinkSync(path.join(directory,file));
  const manifest={version:'1.4.0',categories,songs,excluded,duplicates,sourceCount:audit.entries.length};
  fs.writeFileSync(path.join(root,'assets','music-catalog.js'),'/* Generated by scripts/build-music-catalog.js */\nwindow.GdqMusicCatalog = '+JSON.stringify(manifest,null,2)+';\n');
  fs.writeFileSync(path.join(root,'qa','music-catalog-build.json'),JSON.stringify(manifest,null,2));
  console.log('Bundled music:',songs.length,'tracks;',assets.size,'media files;',excluded.length,'invalid;',duplicates.length,'duplicates omitted.');
  return manifest;
}
if(require.main===module)buildMusicCatalog();
module.exports={buildMusicCatalog};
