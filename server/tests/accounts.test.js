import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createApplication} from '../src/server.js';
test('verified accounts, server roles, shared revisions, lock/expiry, reset and private assets',async()=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'gdqpan-accounts-'));
  const app=createApplication({data:dir,local:true});await new Promise(r=>app.server.listen(0,'127.0.0.1',r));
  const base='http://127.0.0.1:'+app.server.address().port;let admin,user;
  const call=async(route,method='GET',body,token)=>{const r=await fetch(base+'/api'+route,{method,headers:{...(token?{Authorization:'Bearer '+token}:{}),...(body?{'Content-Type':'application/json'}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()};};
  const link=()=>new URL(app.inbox.at(-1).text.match(/http[^\s]+/)[0]);
  try{
    await app.createAdmin('test-admin@example.test','Test-only-password-123');
    assert.equal((await call('/auth/register','POST',{email:'gdqpan-qa-student@gmail.com',password:'Student-password-123'})).status,200);
    assert.equal((await call('/auth/login','POST',{email:'gdqpan-qa-student@gmail.com',password:'Student-password-123'})).status,403);
    const verify=link().searchParams.get('verify');assert(verify);
    assert.equal((await call('/auth/verify','POST',{token:verify})).status,200);
    assert.equal((await call('/auth/verify','POST',{token:verify})).status,400);
    admin=(await call('/auth/login','POST',{email:'test-admin@example.test',password:'Test-only-password-123'})).data;
    await call('/admin/users/'+app.db.prepare('SELECT id FROM users WHERE email=?').get('gdqpan-qa-student@gmail.com').id,'PATCH',{approval:'approved'},admin.token);
    user=(await call('/auth/login','POST',{email:'gdqpan-qa-student@gmail.com',password:'Student-password-123',role:'admin'})).data;
    assert.equal(user.user.role,'user');
    assert.equal((await call('/admin/users','GET',null,user.token)).status,403);
    const snapshot=(await call('/shared','GET',null,admin.token)).data;
    snapshot.schedules.push({id:'test-alarm',time:'23:59',days:[0,1,2,3,4,5,6],action:'Báo thức',on:true,text:''});
    assert.equal((await call('/shared','PUT',snapshot,user.token)).status,403);
    const changed=await call('/shared','PUT',snapshot,admin.token);assert.equal(changed.status,200);
    assert.equal((await call('/shared','PUT',snapshot,admin.token)).status,409);
    assert.equal((await call('/authorize','POST',{scheduleId:'test-alarm',revision:0},user.token)).status,409);
    assert.equal((await call('/authorize','POST',{scheduleId:'test-alarm',revision:changed.data.revision},user.token)).status,200);
    const r=await fetch(base+'/api/files',{method:'POST',headers:{Authorization:'Bearer '+admin.token,'Content-Type':'audio/wav'},body:Buffer.from('test-wave')});assert.equal(r.status,201);const file=await r.json();
    assert.equal((await fetch(base+'/api/files/'+file.id,{headers:{Authorization:'Bearer '+user.token}})).status,403);
    changed.data.files.push({id:file.id,kind:'studio',key:file.id,name:'Wave'});assert.equal((await call('/shared','PUT',changed.data,admin.token)).status,200);
    assert.equal((await fetch(base+'/api/files/'+file.id,{headers:{Authorization:'Bearer '+user.token}})).status,200);
    const latest=(await call('/shared','GET',null,admin.token)).data;
    latest.schedules=[];await call('/shared','PUT',latest,admin.token);
    assert.equal((await call('/authorize','POST',{scheduleId:'test-alarm',revision:changed.data.revision},user.token)).status,200);
    assert.equal((await fetch(base+'/api/files',{method:'POST',headers:{Authorization:'Bearer '+user.token,'Content-Type':'audio/wav'},body:'x'})).status,403);
    assert.equal((await call('/admin/users/'+user.user.id,'PATCH',{status:'locked',expires:null},admin.token)).status,200);
    assert.equal((await call('/authorize','POST',{},user.token)).status,403);
    await call('/admin/users/'+user.user.id,'PATCH',{status:'active',expires:Date.now()-1000},admin.token);
    assert.equal((await call('/session','GET',null,user.token)).status,403);
    await call('/admin/users/'+user.user.id,'PATCH',{status:'active',expires:null},admin.token);
    assert.equal((await call('/session','GET',null,user.token)).status,200);
    await call('/auth/forgot','POST',{email:'gdqpan-qa-student@gmail.com'});const reset=link().searchParams.get('reset');
    assert.equal((await call('/auth/reset','POST',{token:reset,password:'Updated-password-456'})).status,200);
    assert.equal((await call('/session','GET',null,user.token)).status,401);
    assert.equal((await call('/auth/reset','POST',{token:reset,password:'Updated-password-456'})).status,400);
    assert.equal((await call('/auth/login','POST',{email:'gdqpan-qa-student@gmail.com',password:'Updated-password-456'})).status,200);
    assert.equal((await call('/admin/users/'+admin.user.id,'PATCH',{status:'locked',expires:null},admin.token)).status,400);
    assert.equal((await fetch(base+'/.env')).status,404);
    assert.equal((await fetch(base+'/api/session',{headers:{Origin:'https://untrusted.example',Authorization:'Bearer '+admin.token}})).status,403);
  }finally{await new Promise(r=>app.server.close(r));app.close();fs.rmSync(dir,{recursive:true,force:true});}
});
